// Helper function to calculate nutrition based on weight
export function calculateNutrition(foodItem: FoodItem, weightInGrams: number): {
  calories: number;
  proteins: number;
  carbs: number;
  fats: number;
  fiber: number;
} {
  const multiplier = weightInGrams / foodItem.servingSizeGrams;
  
  return {
    calories: Math.round(foodItem.calories * multiplier),
    proteins: +(foodItem.proteins * multiplier).toFixed(1),
    carbs: +(foodItem.carbs * multiplier).toFixed(1),
    fats: +(foodItem.fats * multiplier).toFixed(1),
    fiber: +(foodItem.fiber * multiplier).toFixed(1)
  };
}

// Get all food categories
export function getFoodCategories(): string[] {
  const categoriesSet = new Set<string>();
  foodDatabase.forEach(item => categoriesSet.add(item.category));
  return Array.from(categoriesSet);
}

// Get food items by category
export function getFoodItemsByCategory(category: string): FoodItem[] {
  return foodDatabase.filter(item => item.category === category);
}

// Search food items by name (supports both English and Arabic)
export function searchFoodItems(query: string): FoodItem[] {
  if (!query || query.trim() === '') return [];
  const normalizedQuery = query.toLowerCase().trim();
  return foodDatabase.filter(item => {
    const englishMatch = item.name.toLowerCase().includes(normalizedQuery);
    const arabicMatch = item.nameAr && item.nameAr.includes(query.trim());
    return englishMatch || arabicMatch;
  });
}

// Get food item by ID
export function getFoodItemById(id: number): FoodItem | undefined {
  return foodDatabase.find(item => item.id === id);
}